"""Run the bounded Ubuntu CPU formula replacement sweep without changing services.

Defaults: 12 native topologies x 90 seconds, top two plus 7/1 reference x three
180-second verified mTLS confirmations, then a 1200-second selected-config soak.
All endpoints are temporary random loopback ports. No API policy is changed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import signal
import socket
import statistics
import subprocess
import sys
import time

from recognition_cpu import write_json
from recognition_http import connection


def interpreter_path(path):
    # Resolving a venv/bin/python symlink selects the base runtime and loses its
    # site-packages. Pass the environment's own executable path to subprocesses.
    return Path(path).expanduser().absolute()


def preflight_runtime(python, kind, modules):
    code = "import importlib,json,sys;[importlib.import_module(name) for name in sys.argv[1:]];print(json.dumps({'executable':sys.executable,'prefix':sys.prefix}))"
    completed = subprocess.run([str(python), "-c", code, *modules], env=environment(), text=True,
                               capture_output=True, timeout=120)
    if completed.returncode:
        raise RuntimeError(f"{kind} interpreter dependency preflight failed: {python}\n{completed.stderr[-6000:]}")
    return json.loads(completed.stdout.strip().splitlines()[-1])


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def fingerprint(args, cores):
    """Bind reusable screen measurements to their complete execution inputs."""
    files = {}
    for service in ("TableStructureRec", "FormulaRecognition"):
        directory = args.root / "services" / service
        for current, dirs, names in os.walk(directory):
            dirs[:] = [name for name in dirs if name not in ("venv", ".venv", "models", "logs", ".git", "__pycache__", ".pytest_cache")]
            for name in names:
                if name.endswith(".py") or name in ("model-manifest.json", "requirements-cpu.lock", "requirements-test-cpu.lock"):
                    path = Path(current) / name
                    files[path.relative_to(args.root).as_posix()] = sha256(path)
    for name in ("recognition_cpu.py", "recognition_http.py", "sweep_formula_cpu.py"):
        path = args.root / "scripts/benchmarks" / name
        files[path.relative_to(args.root).as_posix()] = sha256(path)
    # The fourth table input is generated by the hashed benchmark source and
    # Pillow runtime; these three inputs are loaded from fixture bytes.
    table_fixtures = args.root / "services/TableStructureRec/tests/test_files"
    for name in ("wired/table1.png", "lineless_table_recognition.jpg", "table.jpg"):
        path = table_fixtures / name
        files[path.relative_to(args.root).as_posix()] = sha256(path)
    manifest = args.root / "services/FormulaRecognition/tests/corpus/manifest.json"
    files[manifest.relative_to(args.root).as_posix()] = sha256(manifest)
    entries = json.loads(manifest.read_text(encoding="utf-8"))
    if isinstance(entries, dict):
        entries = entries["fixtures"]
    for entry in entries:
        path = manifest.parent / entry["image"]
        files[path.relative_to(args.root).as_posix()] = sha256(path)
    artifacts = {}
    runtimes = {}
    for kind, service in (("table", "TableStructureRec"), ("latex", "FormulaRecognition")):
        model_dir = getattr(args, f"{kind}_model_dir")
        model_manifest = json.loads((args.root / "services" / service / "model-manifest.json").read_text(encoding="utf-8"))
        artifacts[kind] = {"directory": str(model_dir), "files": {item["path"]: sha256(model_dir / item["path"]) for item in model_manifest["files"]}}
        command = [str(getattr(args, f"{kind}_python")), "-c",
                   "import importlib.metadata,json,sys;print(json.dumps({'python':sys.version,'packages':sorted((d.metadata['Name'],d.version) for d in importlib.metadata.distributions())}))"]
        runtimes[kind] = json.loads(subprocess.check_output(command, text=True, env=environment()))
    cpu = subprocess.check_output(["lscpu", "-J"], text=True)
    hardware = {item["field"]: item["data"] for item in json.loads(cpu)["lscpu"] if item["field"] in
                ("Architecture:", "CPU(s):", "Model name:", "Vendor ID:", "Socket(s):", "Core(s) per socket:", "Thread(s) per core:")}
    governors = sorted({path.read_text().strip() for path in Path("/sys/devices/system/cpu").glob("cpu*/cpufreq/scaling_governor")})
    env = environment()
    value = {"files": files, "model_artifacts": artifacts, "runtimes": runtimes,
             "hardware": {"platform": platform.platform(), "lscpu": hardware, "physical_cores": cores, "governors": governors},
             "environment": {key: env[key] for key in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS", "TOKENIZERS_PARALLELISM", "PADDLE_PDX_DISABLE_MODEL_SOURCE_CHECK")},
             "durations": {"screen_seconds": args.screen_seconds, "confirm_seconds": args.confirm_seconds, "soak_seconds": args.soak_seconds, "repeats": args.repeats},
             "candidate_limit": args.candidate_limit}
    value["sha256"] = hashlib.sha256(json.dumps(value, sort_keys=True).encode()).hexdigest()
    return value


def physical_cores():
    data = json.loads(subprocess.check_output(["lscpu", "-J", "-e=CPU,CORE,SOCKET,ONLINE"], text=True))
    allowed = os.sched_getaffinity(0)
    groups = {}
    for item in data["cpus"]:
        cpu = int(item["cpu"])
        if cpu in allowed and str(item.get("online", "yes")).lower() in ("yes", "true", "1"):
            groups.setdefault((int(item["socket"]), int(item["core"])), []).append(cpu)
    result = [sorted(values) for _, values in sorted(groups.items())]
    if len(result) < 8:
        raise ValueError("The approved sweep requires eight available physical cores")
    return result[:8]


def topologies(cores):
    flatten = lambda values: [cpu for core in values for cpu in core]
    result = []
    for formula_cores in range(1, 5):
        table_cores = 8 - formula_cores
        for formula_threads in sorted({1, min(2, formula_cores), formula_cores}):
            result.append({"name": f"split-{table_cores}-{formula_cores}-f{formula_threads}", "formula_cores": formula_cores,
                           "table_threads": table_cores, "latex_threads": formula_threads,
                           "table_affinity": flatten(cores[:table_cores]), "latex_affinity": flatten(cores[table_cores:])})
    for threads in (1, 2, 4):
        result.append({"name": f"shared-f{threads}", "formula_cores": 8, "table_threads": 8, "latex_threads": threads,
                       "table_affinity": flatten(cores), "latex_affinity": flatten(cores)})
    return result


def terminate(processes):
    for process in processes:
        if getattr(process, "benchmark_process_group", False):
            try:
                os.killpg(process.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
        elif process.poll() is None:
            process.terminate()
    for process in processes:
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()
        # The controller can have exited while a native child is still alive.
        if getattr(process, "benchmark_process_group", False):
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass


def environment():
    env = os.environ.copy()
    env.pop("LATEX_REC_EXECUTION_PROVIDER", None)
    env.update(OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1", MKL_NUM_THREADS="1",
               NUMEXPR_NUM_THREADS="1", TOKENIZERS_PARALLELISM="false",
               PADDLE_PDX_DISABLE_MODEL_SOURCE_CHECK="True", PYTHONUNBUFFERED="1")
    return env


def native(args, candidate):
    directory = args.output_dir / "screen" / candidate["name"]
    directory.mkdir(parents=True, exist_ok=True)
    barrier = directory / "barrier"
    # Refuse stale barrier state rather than accidentally starting one service early.
    if barrier.exists():
        raise ValueError(f"Existing barrier directory: {barrier}; use a fresh output directory or --reuse-screen")
    processes, streams = [], []
    try:
        for kind, service in (("table", "TableStructureRec"), ("latex", "FormulaRecognition")):
            stream = (directory / f"{kind}.log").open("w", encoding="utf-8")
            streams.append(stream)
            command = [str(getattr(args, f"{kind}_python")), str(args.root / "scripts/benchmarks/recognition_cpu.py"),
                       "--service", kind, "--root", str(args.root / "services" / service),
                       "--model-dir", str(getattr(args, f"{kind}_model_dir")), "--workers", "1",
                       "--threads", str(candidate[f"{kind}_threads"]), "--affinity", ",".join(map(str, candidate[f"{kind}_affinity"])),
                       "--cycles", "0", "--seconds", str(args.screen_seconds), "--barrier-dir", str(barrier),
                       "--output", str(directory / f"{kind}.json")]
            process = subprocess.Popen(command, env=environment(), stdout=stream, stderr=subprocess.STDOUT,
                                       start_new_session=sys.platform == "linux")
            process.benchmark_process_group = sys.platform == "linux"
            processes.append(process)
        timeout = time.monotonic() + 300
        while not all((barrier / f"{kind}.ready.json").exists() for kind in ("table", "latex")):
            if any(process.poll() is not None for process in processes) or time.monotonic() > timeout:
                raise RuntimeError(f"Native warmup failed: inspect {directory}")
            time.sleep(.1)
        write_json(barrier / "start.json", {"start_monotonic": time.monotonic() + .3})
        for process in processes:
            if process.wait(timeout=args.screen_seconds + 150) != 0:
                raise RuntimeError(f"Native measurement failed: inspect {directory}")
        reports = {kind: json.loads((directory / f"{kind}.json").read_text(encoding="utf-8-sig")) for kind in ("table", "latex")}
        return {"configuration": candidate, "balanced_capacity_rps": min(report["throughput_rps"] for report in reports.values()),
                "reports": {kind: str(directory / f"{kind}.json") for kind in reports}}
    finally:
        terminate(processes)
        for stream in streams:
            stream.close()


def free_port():
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def wait_ready(process, kind, port, pki, timeout=300):
    end = time.monotonic() + timeout
    while process.poll() is None and time.monotonic() < end:
        client = connection(kind, port, pki)
        try:
            client.request("GET", "/health/ready", headers={"Connection": "close"})
            response = client.getresponse()
            response.read()
            if response.status == 200:
                return
        except (OSError, ConnectionError):
            pass
        finally:
            client.close()
        time.sleep(.2)
    raise RuntimeError(f"{kind} temporary worker failed to become ready")


def stop_http_workers(processes, directory, timeout=60):
    """Require successful lifespan teardown before accepting completed HTTP runs."""
    reports, pending = {}, {}
    for kind, process in zip(("table", "latex"), processes):
        started = time.monotonic()
        alive = process.poll() is None
        reports[kind] = {"pid": process.pid, "signal": "SIGTERM", "requested_wall_timestamp": time.time(),
                         "requested_monotonic_timestamp": started, "alive_before_stop": alive, "forced_kill": False}
        if alive:
            process.send_signal(signal.SIGTERM)
        pending[kind] = process
    deadline = time.monotonic() + timeout
    while pending:
        for kind, process in list(pending.items()):
            returncode = process.poll()
            if returncode is not None:
                stopped = time.monotonic()
                reports[kind].update(returncode=returncode, stopped_monotonic_timestamp=stopped,
                                     observed_stop_seconds=stopped - reports[kind]["requested_monotonic_timestamp"])
                del pending[kind]
        if not pending:
            break
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            for kind, process in pending.items():
                reports[kind]["forced_kill"] = True
                if getattr(process, "benchmark_process_group", False):
                    try:
                        os.killpg(process.pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
                else:
                    process.kill()
                returncode = process.wait(timeout=5)
                stopped = time.monotonic()
                reports[kind].update(returncode=returncode, stopped_monotonic_timestamp=stopped,
                                     observed_stop_seconds=stopped - reports[kind]["requested_monotonic_timestamp"])
            break
        time.sleep(min(.02, remaining))
    errors = []
    for kind, report in reports.items():
        log = directory / f"{kind}.log"
        text = log.read_text(encoding="utf-8", errors="replace")
        report.update(log_file=log.name, lifespan_marker_required=kind == "latex",
                      worker_stopped=bool(re.search(rf"\bworker_stopped\s+worker_pid={report['pid']}\b", text)),
                      paddle_sigterm_fatal="FatalError" in text and ("SIGTERM" in text or "Termination signal" in text))
        if not report["alive_before_stop"]:
            errors.append(f"{kind} worker exited before supervised teardown")
        if report["forced_kill"]:
            errors.append(f"{kind} worker exceeded the {timeout:g}s supervisor shutdown bound")
        if report["returncode"] not in (0, -signal.SIGTERM):
            errors.append(f"{kind} worker returned abnormal shutdown status {report['returncode']}")
        if kind == "latex" and not report["worker_stopped"]:
            errors.append("latex worker did not complete its lifespan shutdown")
        if report["paddle_sigterm_fatal"]:
            errors.append(f"{kind} worker logged a Paddle SIGTERM FatalError")
    evidence = {"supervisor_timeout_seconds": timeout, "formula_uvicorn_grace_seconds": 55,
                "observed_exit_poll_resolution_seconds": .02,
                "normal_returncodes": [0, -signal.SIGTERM], "workers": reports, "errors": errors}
    write_json(directory / "worker-teardown.json", evidence)
    if errors:
        raise RuntimeError(f"mTLS worker teardown failed: {errors}; inspect {directory}")
    return evidence


def http_run(args, candidate, label, seconds):
    directory = args.output_dir / label / candidate["name"]
    directory.mkdir(parents=True, exist_ok=True)
    processes, streams, ports = [], [], {}
    try:
        for kind, service, prefix, module in (("table", "TableStructureRec", "TABLE_REC", "table_rec_service"),
                                              ("latex", "FormulaRecognition", "LATEX_REC", "latex_rec_service")):
            port = free_port()
            while port in ports.values():
                port = free_port()
            ports[kind] = port
            pki = args.pki_dir / f"{kind}-communication"
            env = environment()
            env.update({f"{prefix}_HOST": "127.0.0.1", f"{prefix}_PORT": str(port), f"{prefix}_WORKERS": "1",
                        f"{prefix}_CPU_THREADS": str(candidate[f"{kind}_threads"]),
                        f"{prefix}_MODEL_DIR": str(getattr(args, f"{kind}_model_dir")),
                        f"{prefix}_ENVIRONMENT": "production", f"{prefix}_LOG_LEVEL": "info" if kind == "latex" else "warning",
                        f"{prefix}_TLS_CERTIFICATE": str(pki / "worker-server.pem"),
                        f"{prefix}_TLS_PRIVATE_KEY": str(pki / "worker-server-key.pem"),
                        f"{prefix}_TLS_CLIENT_CA": str(pki / "api-client-ca.pem")})
            if kind == "table":
                env["TABLE_REC_EXECUTION_PROVIDER"] = "CPUExecutionProvider"
            stream = (directory / f"{kind}.log").open("w", encoding="utf-8")
            streams.append(stream)
            affinity = candidate[f"{kind}_affinity"]
            process = subprocess.Popen([str(getattr(args, f"{kind}_python")), "-m", module],
                                       cwd=args.root / "services" / service, env=env, stdout=stream, stderr=subprocess.STDOUT,
                                       start_new_session=True,
                                       preexec_fn=lambda cpus=affinity: os.sched_setaffinity(0, cpus))
            process.benchmark_process_group = True
            processes.append(process)
        for kind, process in zip(("table", "latex"), processes):
            wait_ready(process, kind, ports[kind], args.pki_dir)
        output = directory / "http.json"
        command = [str(args.latex_python), str(args.root / "scripts/benchmarks/recognition_http.py"),
                   "--root", str(args.root), "--pki-dir", str(args.pki_dir), "--seconds", str(seconds),
                   "--table-port", str(ports["table"]), "--latex-port", str(ports["latex"]),
                   "--table-pid", str(processes[0].pid), "--latex-pid", str(processes[1].pid), "--output", str(output)]
        with (directory / "client.log").open("w", encoding="utf-8") as stream:
            completed = subprocess.run(command, env=environment(), stdout=stream, stderr=subprocess.STDOUT, timeout=seconds + 900)
        if completed.returncode or any(process.poll() is not None for process in processes):
            raise RuntimeError(f"mTLS benchmark failed: inspect {directory}")
        report = json.loads(output.read_text(encoding="utf-8-sig"))
        if report["errors"] or any(row.get(kind, {}).get("VmSwap", 0) for row in report["memory_samples"] for kind in ("table", "latex")):
            raise RuntimeError(f"mTLS benchmark recorded errors or swap: {output}")
        report["worker_teardown"] = stop_http_workers(processes, directory)
        # Preserve the client's raw report mtime for supplemental CPU interval
        # reconstruction; teardown evidence is saved in its own adjacent file.
        return report
    finally:
        terminate(processes)
        for stream in streams:
            stream.close()


def selection(candidates, confirmations, reference):
    rates = {candidate["name"]: [report["balanced_pairs_rps"] for report in confirmations[candidate["name"]]] for candidate in candidates}
    baseline = rates[reference["name"]]
    required_wins = len(baseline) // 2 + 1
    eligible = [candidate for candidate in candidates if candidate["name"] == reference["name"]
                or sum(rate >= ref for rate, ref in zip(rates[candidate["name"]], baseline)) >= required_wins]
    best = max(eligible, key=lambda candidate: statistics.median(rates[candidate["name"]]))
    best_median = statistics.median(rates[best["name"]])
    tied = [candidate for candidate in eligible if statistics.median(rates[candidate["name"]]) >= best_median * .97]
    selected = min(tied, key=lambda candidate: (candidate["formula_cores"], candidate["latex_threads"]))
    return selected, {"rates": rates, "median_rates": {name: statistics.median(values) for name, values in rates.items()},
                      "selection_rule": "Must meet the 7/1 reference in a majority of paired rounds; maximize median balanced pairs/s; medians within 3% of best prefer fewer formula cores, then threads"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--table-python", type=Path, required=True)
    parser.add_argument("--latex-python", type=Path, required=True)
    parser.add_argument("--table-model-dir", type=Path)
    parser.add_argument("--latex-model-dir", type=Path)
    parser.add_argument("--pki-dir", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--stage", choices=("screen", "full"), default="full")
    parser.add_argument("--reuse-screen", action="store_true")
    parser.add_argument("--screen-seconds", type=float, default=90)
    parser.add_argument("--confirm-seconds", type=float, default=180)
    parser.add_argument("--soak-seconds", type=float, default=1200)
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--candidate-limit", type=int, default=12, help="Reduce only for smoke tests; release sweep uses 12")
    args = parser.parse_args()
    if sys.platform != "linux":
        parser.error("Run on Ubuntu/WSL Linux CPU")
    if min(args.screen_seconds, args.confirm_seconds, args.soak_seconds) <= 0 or args.repeats < 1 or not 1 <= args.candidate_limit <= 12:
        parser.error("Invalid durations, repeats or candidate limit")
    for name in ("root", "table_python", "latex_python", "output_dir", "pki_dir", "table_model_dir", "latex_model_dir"):
        value = getattr(args, name)
        if value is not None:
            setattr(args, name, interpreter_path(value) if name.endswith("_python") else value.expanduser().resolve())
    args.table_model_dir = args.table_model_dir or args.root / "services/TableStructureRec/models"
    args.latex_model_dir = args.latex_model_dir or args.root / "services/FormulaRecognition/models"
    if args.stage == "full" and not args.pki_dir:
        parser.error("--pki-dir is required for local mTLS confirmation")
    preflight = {
        "table": preflight_runtime(args.table_python, "table", ["cv2", "PIL", "numpy", "onnxruntime"]),
        "latex": preflight_runtime(args.latex_python, "latex", ["cv2", "PIL", "numpy", "paddle", "paddlex"]),
    }
    cores = physical_cores()
    candidates = topologies(cores)[:args.candidate_limit]
    reference = candidates[0]
    args.output_dir.mkdir(parents=True, exist_ok=True)
    identity = fingerprint(args, cores)
    summary = {"host": {"platform": platform.platform(), "physical_cores": cores},
               "runtime_preflight": preflight,
               "fingerprint": identity,
               "method": {"screen_seconds": args.screen_seconds, "confirmation_seconds": args.confirm_seconds,
                          "confirmation_repeats": args.repeats, "soak_seconds": args.soak_seconds,
                          "processes_per_service": 1, "api_global_concurrency": 1, "p95": "nearest-rank",
                          "http_teardown": "SIGTERM with 60s supervisor bound; require formula PID-specific worker_stopped, normal exit0/-SIGTERM, and no Paddle SIGTERM FatalError; adjacent worker-teardown.json records stop evidence"},
               "screen": [], "errors": []}
    for candidate in candidates:
        print(f"SCREEN {candidate['name']}", flush=True)
        cached = args.output_dir / "screen" / candidate["name"] / "configuration.json"
        try:
            if args.reuse_screen and cached.exists():
                entry = json.loads(cached.read_text(encoding="utf-8-sig"))
                if entry["configuration"] != candidate:
                    raise ValueError("Cached candidate CPU topology differs from this host")
                if entry.get("fingerprint") != identity["sha256"]:
                    raise ValueError("Cached screen fingerprint differs; model, corpus, source, runtime, duration, hardware or environment changed")
            else:
                entry = native(args, candidate)
                entry["fingerprint"] = identity["sha256"]
                write_json(cached, entry)
            summary["screen"].append(entry)
        except Exception as exc:
            summary["errors"].append({"stage": "screen", "configuration": candidate["name"], "error": repr(exc)})
        write_json(args.output_dir / "summary.json", summary)
    if not summary["screen"] or not any(entry["configuration"]["name"] == reference["name"] for entry in summary["screen"]):
        raise RuntimeError("The new-model 7/1 reference must pass before selecting a configuration")
    if args.stage == "screen":
        print(json.dumps(summary, indent=2))
        return
    ranked = sorted(summary["screen"], key=lambda entry: entry["balanced_capacity_rps"], reverse=True)
    finalists = [entry["configuration"] for entry in ranked[:2]]
    if not any(candidate["name"] == reference["name"] for candidate in finalists):
        finalists.append(reference)
    confirmations = {candidate["name"]: [] for candidate in finalists}
    for repeat in range(args.repeats):
        for candidate in (finalists if repeat % 2 == 0 else list(reversed(finalists))):
            print(f"CONFIRM {repeat + 1}/{candidate['name']}", flush=True)
            confirmations[candidate["name"]].append(http_run(args, candidate, f"confirm-{repeat + 1}", args.confirm_seconds))
    selected, evidence = selection(finalists, confirmations, reference)
    summary.update(selected_configuration=selected, confirmation=evidence)
    write_json(args.output_dir / "summary.json", summary)
    print(f"SOAK {selected['name']}", flush=True)
    soak = http_run(args, selected, "soak", args.soak_seconds)
    rss_windows = {}
    for kind in ("table", "latex"):
        points = [(row["seconds"], row.get(kind, {}).get("VmRSS", 0)) for row in soak["memory_samples"]]
        rss_windows[kind] = [{"start_seconds": start, "median_rss_bytes": statistics.median([rss for second, rss in points if start <= second < start + 300])}
                            for start in range(0, int(args.soak_seconds), 300) if any(start <= second < start + 300 for second, _ in points)]
    summary.update(soak={"balanced_pairs_rps": soak["balanced_pairs_rps"], "errors": soak["errors"], "rss_windows": rss_windows},
                   completed=True, production_defaults_changed=False)
    write_json(args.output_dir / "summary.json", summary)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
